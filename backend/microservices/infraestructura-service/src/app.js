const express = require("express");
const campusRoutes = require("./routes/campusRoutes");
const salonRoutes = require("./routes/salonRoutes");
const errorMiddleware = require("./middlewares/errorMiddleware");
const app = express();
app.disable("x-powered-by");
app.use(express.json({ limit: "64kb" }));
app.get("/health", (req,res) => res.json({ servicio: "infraestructura-service", estado: "ok" }));
app.use("/api/v1/campus", campusRoutes);
app.use("/api/v1/salones", salonRoutes);
app.use((req,res) => res.status(404).json({ error: "RUTA_NO_ENCONTRADA" }));
app.use(errorMiddleware);
module.exports = app;
